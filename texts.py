def parties_text() -> str:
    lines = ["<b>ПАРТИИ НА БЮЛЛЕТЕНЕ</b>", ""]
    for p in PARTIES.values():
        leader = f" - {html.escape(p.leader)}" if p.leader != "-" else ""
        lines.append(f"<b>{html.escape(p.name)}</b>{leader}\n{html.escape(p.short)}")
        lines.append("")
    lines.append("Новые партии которые выросли уже после кризиса и войны сюда не запихнуты задним числом. Иначе это были бы выборы 2059 с DLC из 2061")
    return "\n".join(lines)


