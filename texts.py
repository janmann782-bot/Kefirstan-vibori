def parties_text() -> str:
    lines = ["<b>ПАРТИИ НА БЮЛЛЕТЕНЕ</b>", ""]
    for p in PARTIES.values():
        leader = f" - {html.escape(p.leader)}" if p.leader != "-" else ""
        lines.append(f"{PARTY_MARKERS[p.code]} <b>{html.escape(p.name)}</b>{leader}\n{html.escape(p.short)}")
        lines.append("")
    lines.append("Партий которые появятся уже после войны и мятежа здесь нет. Все-таки сейчас 2059, а не сборная солянка из будущего")
    return "\n".join(lines)


